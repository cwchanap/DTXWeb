import { test, expect, type Page } from '@playwright/test';
import { PAGES } from './constants';
import { CHART_D_ID, DTX_API_LOCAL_PORT } from './test-config';
import { parseMidi, type ParsedMidi } from '@dtx/common';
import { readFileSync } from 'node:fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const parseFixture = (name: string): ParsedMidi =>
	parseMidi(new Uint8Array(readFileSync(path.join(__dirname, 'fixtures', name))));

// Mirror the page's display formatters so every asserted value is computed
// from the same parser output the component renders.
const formatTime = (seconds: number): string =>
	`${Math.floor(seconds / 60)}:${Math.floor(seconds % 60)
		.toString()
		.padStart(2, '0')}`;

const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const noteName = (note: number): string => `${NOTE_NAMES[note % 12]}${Math.floor(note / 12) - 1}`;

// In the metadata grid the value div precedes its label ("0"/"Format"); in the
// detail rows and track cards the value follows it ("Tempo"/"120 BPM").
const gridValue = (page: Page, label: string) =>
	page.locator(`xpath=//div[normalize-space()="${label}"]/preceding-sibling::div[1]`);
const detailValue = (page: Page, label: string) =>
	page.locator(`xpath=//div[normalize-space()="${label}"]/following-sibling::div[1]`);

test.describe('MIDI Preview Tool', () => {
	// Test fixture paths (generated by TypeScript create-test-midi.ts)
	const testMidiPath = path.join(__dirname, 'fixtures', 'test-sample.mid');
	const drumOffGridPath = path.join(__dirname, 'fixtures', 'drum-off-grid.mid');

	test.describe('Navigation and Initial State', () => {
		test('opens the MIDI preview tool page', async ({ page }) => {
			await page.goto(PAGES.TOOLS);
			await page.waitForSelector('html[data-e2e-hydrated="true"]');

			// Verify tools page loads
			await expect(page.getByRole('heading', { name: 'Available Tools' })).toBeVisible();

			// Verify MIDI Preview tool is available
			await expect(page.getByRole('heading', { name: 'MIDI Preview' })).toBeVisible();
			await expect(
				page.getByText('Preview and analyze MIDI files with track information and playback')
			).toBeVisible();

			await page.goto(PAGES.MIDI_PREVIEW);
			await expect(page).toHaveURL(PAGES.MIDI_PREVIEW);
			await expect(
				page.getByRole('heading', { name: 'MIDI Preview', level: 1 })
			).toBeVisible();
		});
	});

	test.describe('File Upload Functionality', () => {
		test('should upload and parse a valid MIDI file with notes', async ({ page }) => {
			await page.goto(PAGES.MIDI_PREVIEW);
			await page.waitForLoadState('networkidle');
			await page.waitForSelector('html[data-e2e-hydrated="true"]');

			// Upload file
			await page.setInputFiles('input[type="file"]', testMidiPath);

			// Verify file information is displayed
			await expect(page.getByRole('heading', { name: 'File Loaded' })).toBeVisible({
				timeout: 10000
			});
			await expect(page.getByText('test-sample.mid')).toBeVisible();

			// Verify file information section appears
			await expect(page.getByRole('heading', { name: 'File Information' })).toBeVisible();
			await expect(page.getByText('Format', { exact: true })).toBeVisible();
			await expect(page.getByText('Tracks', { exact: true })).toBeVisible();
			await expect(page.getByText('Total Notes', { exact: true })).toBeVisible();
			await expect(page.getByText('Duration', { exact: true })).toBeVisible();
			await expect(page.getByText('Tempo', { exact: true })).toBeVisible();
			await expect(page.getByText(/\bBPM\b/)).toBeVisible();

			// Verify track details section appears
			await expect(page.getByRole('heading', { name: 'Track Details' })).toBeVisible();
		});

		test('displays the shared parser metadata and per-track details', async ({ page }) => {
			const expected = parseFixture('test-sample.mid');

			await page.goto(PAGES.MIDI_PREVIEW);
			await page.waitForSelector('html[data-e2e-hydrated="true"]');
			await page.setInputFiles('input[type="file"]', testMidiPath);
			await expect(page.getByRole('heading', { name: 'File Information' })).toBeVisible({
				timeout: 10000
			});

			await expect(gridValue(page, 'Format')).toHaveText(String(expected.format));
			await expect(gridValue(page, 'Tracks')).toHaveText(String(expected.trackCount));
			await expect(gridValue(page, 'Total Notes')).toHaveText(String(expected.totalNotes));
			await expect(gridValue(page, 'Duration')).toHaveText(formatTime(expected.duration));
			await expect(detailValue(page, 'Tempo')).toHaveText(`${expected.tempo} BPM`);
			await expect(detailValue(page, 'Ticks per Quarter')).toHaveText(
				String(expected.ticksPerQuarter)
			);

			// Track card mirrors the parsed track: name, note count, channels and
			// computed note range. Scoped to the card — the success toast also
			// contains "${n} notes" and would trip strict mode.
			const track = expected.tracks[0];
			const trackCard = page
				.locator('div.rounded-lg')
				.filter({ has: page.getByRole('heading', { name: `Track 1 - ${track.name}` }) });
			await expect(trackCard).toBeVisible();
			await expect(
				trackCard.getByText(`${track.notes.length} notes`, { exact: true })
			).toBeVisible();
			await expect(detailValue(page, 'Channels')).toHaveText(
				Array.from(track.channels)
					.sort((a, b) => a - b)
					.join(', ')
			);
			const notes = track.notes.map((n) => n.note);
			await expect(detailValue(page, 'Note Range')).toHaveText(
				`${noteName(Math.min(...notes))} - ${noteName(Math.max(...notes))}`
			);
		});

		test('displays off-grid drum fixture truthfully (960 PPQ, mixed channels)', async ({
			page
		}) => {
			const expected = parseFixture('drum-off-grid.mid');

			await page.goto(PAGES.MIDI_PREVIEW);
			await page.waitForSelector('html[data-e2e-hydrated="true"]');
			await page.setInputFiles('input[type="file"]', drumOffGridPath);
			await expect(page.getByRole('heading', { name: 'File Information' })).toBeVisible({
				timeout: 10000
			});

			await expect(gridValue(page, 'Total Notes')).toHaveText(String(expected.totalNotes));
			await expect(detailValue(page, 'Tempo')).toHaveText(`${expected.tempo} BPM`);
			await expect(detailValue(page, 'Ticks per Quarter')).toHaveText('960');

			// Both the drum channel and the foreign channel surface in the card.
			const track = expected.tracks[0];
			await expect(detailValue(page, 'Channels')).toHaveText(
				Array.from(track.channels)
					.sort((a, b) => a - b)
					.join(', ')
			);
			const notes = track.notes.map((n) => n.note);
			await expect(detailValue(page, 'Note Range')).toHaveText(
				`${noteName(Math.min(...notes))} - ${noteName(Math.max(...notes))}`
			);
		});
	});
});

test.describe('SET.def catalog pairing (chart 1004)', () => {
	const API_URL = `http://localhost:${DTX_API_LOCAL_PORT}/graphql`;

	test('worker pairs mixed-form SET.def files to dtx rows, duplicates and L6 included', async ({
		page
	}) => {
		// Chart 1004 is seeded with a SET.def mixing colon/whitespace directive
		// forms, two "Basic Multi" labels, an L6 slot and a subdirectory file
		// reference. The Worker's R2 enrichment must pair each dtx_files row
		// FIFO by label — not collapse duplicates or fall back to song.dtx.
		const res = await page.request.post(API_URL, {
			headers: {
				'content-type': 'application/json',
				Origin: 'http://localhost:5173'
			},
			data: {
				query: `query { simfile(id: "${CHART_D_ID}") { dtxFiles { label level fileUrl } } }`
			}
		});
		expect(res.ok(), `GraphQL request failed: ${res.status()}`).toBe(true);
		const body = (await res.json()) as {
			data?: {
				simfile?: { dtxFiles: { label: string; level: number; fileUrl: string | null }[] };
			};
			errors?: { message: string }[];
		};
		expect(body.errors ?? []).toEqual([]);
		const rows = body.data?.simfile?.dtxFiles ?? [];
		expect(rows).toHaveLength(4);

		const bucket = 'https://chart.hapadona.com';
		const fileFor = (label: string, level: number): string | null =>
			rows.find((r) => r.label === label && r.level === level)?.fileUrl ?? null;

		// Single-label row resolves its namesake chart.
		expect(fileFor('Basic Easy', 40)).toBe(`${bucket}/${CHART_D_ID}/basic.dtx`);
		// Duplicate labels pair FIFO with the SET.def slot order — two distinct
		// fileUrls, not the same object twice.
		expect(fileFor('Basic Multi', 50)).toBe(`${bucket}/${CHART_D_ID}/extra.dtx`);
		expect(fileFor('Basic Multi', 60)).toBe(`${bucket}/${CHART_D_ID}/maniac.dtx`);
		// L6 slot with a subdirectory reference resolves relative to set.def.
		expect(fileFor('Extreme L6', 85)).toBe(`${bucket}/${CHART_D_ID}/sub/lead.dtx`);
	});
});
