// Reparse a downloaded .dtx the same way the app reads charts: parse headers,
// then collect lane -> [measure, position] hits ('00' rest cells excluded).
const hitsByLane = (dtxText: string): Map<string, [number, number][]> => {
	const dtx = new DTXFile(dtxText);
	dtx.parseFromText(dtxText);
	const byLane = new Map<string, [number, number][]>();
	for (const group of dtx.parseNotes()) {
		for (const n of group.notes) {
			if (n.noteID === '00') continue;
			byLane.set(group.laneID, [
				...(byLane.get(group.laneID) ?? []),
				[group.measure, n.position]
			]);
		}
	}
	return byLane;
};

const parseHeaders = (dtxText: string): DTXFile => {
	const dtx = new DTXFile(dtxText);
	dtx.parseFromText(dtxText);
	return dtx;
};

const readDownload = async (download: { path: () => Promise<string | null> }): Promise<string> => {
	const downloadPath = await download.path();
	expect(downloadPath).toBeTruthy();
	return readFileSync(downloadPath!, 'utf-8');
};

test.describe('MIDI to DTX Converter Tool', () => {
	// Test fixture paths (generated by fixtures/create-test-midi.ts)
	const testMidiPath = path.join(__dirname, 'fixtures', 'test-sample.mid');
	const drumConvertPath = path.join(__dirname, 'fixtures', 'drum-convert.mid');
	const drumOffGridPath = path.join(__dirname, 'fixtures', 'drum-off-grid.mid');

	test.describe('Navigation and Initial State', () => {
		test('should navigate from tools page to MIDI to DTX converter', async ({ page }) => {
			await page.goto(PAGES.TOOLS);
			await page.waitForSelector('html[data-e2e-hydrated="true"]');

			// Verify tools page loads
			await expect(page.getByRole('heading', { name: 'Available Tools' })).toBeVisible();

			// Verify MIDI to DTX Converter tool is available
			await expect(
				page.getByRole('heading', { name: 'MIDI to DTX Converter' })
			).toBeVisible();
			await expect(
				page.getByText('Convert MIDI files to DTX drum chart format for rhythm game use')
			).toBeVisible();
			await page.goto(PAGES.MIDI_TO_DTX_CONVERTER);
			await page.waitForLoadState('networkidle');
			await page.waitForSelector('html[data-e2e-hydrated="true"]');
			await expect(page).toHaveURL(PAGES.MIDI_TO_DTX_CONVERTER);
			await expect(
				page.getByRole('heading', { name: 'MIDI to DTX Converter', level: 1 })
			).toBeVisible();
		});
	});

	test.describe('File Upload Functionality', () => {
		test('should upload a valid MIDI file', async ({ page }) => {
			await page.goto(PAGES.MIDI_TO_DTX_CONVERTER);
			await page.waitForLoadState('networkidle');
			await page.waitForSelector('html[data-e2e-hydrated="true"]');

			// Upload file
			await page.setInputFiles('input[type="file"]', testMidiPath);

			// Verify file is uploaded and UI updates
			await expect(page.getByRole('heading', { name: 'File Ready' })).toBeVisible({
				timeout: 10000
			});
			await expect(page.getByText('test-sample.mid')).toBeVisible();
			await expect(page.getByText(/\d+\.\d+ KB/)).toBeVisible({ timeout: 10000 });

			// Verify file action buttons appear
			await expect(page.getByRole('button', { name: 'Remove' })).toBeVisible();
			await expect(page.getByRole('button', { name: 'Choose Different File' })).toBeVisible();

			// Verify DTX metadata section appears
			await expect(page.getByRole('heading', { name: 'DTX File Settings' })).toBeVisible();
			await expect(page.getByLabel('Title')).toBeVisible();
			await expect(page.getByLabel('Artist')).toBeVisible();
			await expect(page.getByLabel('Difficulty Level')).toBeVisible();
			await expect(page.getByLabel('BPM')).toBeVisible();
			await expect(page.getByLabel('Comment')).toBeVisible();

			// Verify MIDI note mapping section appears
			await expect(
				page.getByRole('heading', { name: 'MIDI Note to DTX Lane Mapping' })
			).toBeVisible();
		});

		test('shows real drum labels and only playable lanes in the mapping table', async ({
			page
		}) => {
			await page.goto(PAGES.MIDI_TO_DTX_CONVERTER);
			await page.waitForSelector('html[data-e2e-hydrated="true"]');
			await page.setInputFiles('input[type="file"]', drumConvertPath);
			await expect(page.getByRole('heading', { name: 'File Ready' })).toBeVisible({
				timeout: 10000
			});

			// One row per GM import-lane entry, each labelled with the aliased
			// instrument name (never "Unknown").
			const selects = page.locator('select');
			await expect(selects).toHaveCount(Object.keys(GM_IMPORT_LANE).length);
			await expect(page.getByText('Bass (36):', { exact: true })).toBeVisible();
			await expect(page.getByText('Snare (38):', { exact: true })).toBeVisible();
			await expect(page.getByText('Closed Hi-Hat (42):', { exact: true })).toBeVisible();
			await expect(page.getByText('Unknown', { exact: true })).toHaveCount(0);

			// Every select offers exactly the playable drum lanes — no control
			// lanes (01/02/03/08) and no duplicate GM-name targets.
			const optionValues = await page
				.locator('select option')
				.evaluateAll((els) => els.map((el) => (el as HTMLOptionElement).value));
			expect(optionValues).toHaveLength(
				Object.keys(GM_IMPORT_LANE).length * PLAYABLE_DRUM_LANES.length
			);
			expect(new Set(optionValues)).toEqual(new Set(PLAYABLE_DRUM_LANES));
		});
	});

	test.describe('Conversion Process', () => {
		test.beforeEach(async ({ page }) => {
			await page.goto(PAGES.MIDI_TO_DTX_CONVERTER);
			await page.waitForLoadState('networkidle');
			await page.waitForSelector('html[data-e2e-hydrated="true"]');
		});

		test('downloads a .dtx that reparses with converted lanes, tempo and meter', async ({
			page
		}) => {
			await page.setInputFiles('input[type="file"]', drumConvertPath);
			await expect(page.getByRole('button', { name: 'Convert to DTX' })).toBeVisible({
				timeout: 10000
			});

			await page.getByRole('button', { name: 'Convert to DTX' }).click();
			await expect(page.getByRole('button', { name: '✓ Converted' })).toBeVisible({
				timeout: 10000
			});

			// 10 note-ons less one same-slot collision; the channel-08 tempo ref
			// and the lane/measure groups must not count toward the summary.
			await expect(page.getByText('Converted 9 note events')).toBeVisible();
			await expect(page.getByText('1 hit(s) dropped by 1/192-slot collisions')).toBeVisible();

			const downloadPromise = page.waitForEvent('download');
			await page.getByRole('button', { name: 'Download DTX File' }).click();
			const download = await downloadPromise;
			expect(download.suggestedFilename()).toBe('drum-convert.dtx');
			await expect(page.getByText('DTX file downloaded successfully!')).toBeVisible({
				timeout: 5000
			});

			const dtxText = await readDownload(download);

			// Base tempo from the MIDI's tick-0 tempo; the mid-bar 180 BPM change
			// survives as a #BPMxx definition plus a channel-08 reference.
			const reparsed = parseHeaders(dtxText);
			expect(reparsed.bpm).toBe(120);
			expect(dtxText).toContain('#BPM: 120');
			expect(dtxText).toContain('#BPM01: 180');
			expect(Object.values(reparsed.parseBPMChanges())).toContain(180);

			// 3/4 bar 0 then back to 4/4 — channel-02 decimal bar lengths.
			expect(reparsed.parseMeasureLengths().get(0)).toBe(0.75);
			expect(reparsed.parseMeasureLengths().get(1)).toBe(1);

			const hits = hitsByLane(dtxText);
			// Simultaneous cross-lane hits at tick 0 retained; 35 folds into 13
			// at 1/3, 40 into 12 at 2/3 (the tick-0 40 was the dropped collision),
			// 53 and 51 into 19, 45 stays late-bar at 5/6 of the 3/4 bar.
			expect(hits.get('13')).toEqual([
				[0, 0],
				[0, 1 / 3]
			]);
			expect(hits.get('12')).toEqual([
				[0, 0],
				[0, 2 / 3],
				[1, 0.375]
			]);
			expect(hits.get('11')).toEqual([[0, 0]]);
			expect(hits.get('19')).toEqual([
				[0, 1 / 6],
				[1, 0]
			]);
			expect(hits.get('15')).toEqual([[0, 5 / 6]]);
			// The 180 BPM ref lands mid-bar 1 at 0.375 under channel 08.
			expect(hits.get('08')).toEqual([[1, 0.375]]);
		});

		test('applies a lane override made after Convert to the downloaded file', async ({
			page
		}) => {
			await page.setInputFiles('input[type="file"]', drumConvertPath);
			await expect(page.getByRole('button', { name: 'Convert to DTX' })).toBeVisible({
				timeout: 10000
			});
			await page.getByRole('button', { name: 'Convert to DTX' }).click();
			await expect(page.getByRole('button', { name: '✓ Converted' })).toBeVisible({
				timeout: 10000
			});

			// Remap GM 36 from its default '13' to high tom '14' after conversion;
			// the download must reflect the latest mapping, not a stale snapshot.
			const row = page.locator('div.flex', {
				has: page.locator('span', { hasText: 'Bass (36):' })
			});
			await row.locator('select').selectOption('14');

			const downloadPromise = page.waitForEvent('download');
			await page.getByRole('button', { name: 'Download DTX File' }).click();
			const download = await downloadPromise;
			const hits = hitsByLane(await readDownload(download));

			expect(hits.get('14')).toEqual([[0, 0]]);
			// The tick-0 36 leaves lane 13; only the 35 alias hit remains there.
			expect(hits.get('13')).toEqual([[0, 1 / 3]]);
		});

		test('reports humanized off-grid hits, unmapped and foreign-channel notes', async ({
			page
		}) => {
			// drum-off-grid.mid: 960 PPQ, 140 BPM, 4/4 -> 3/4 at bar 2, humanized
			// hits, one unmapped GM note (99) and one channel-0 note (ignored).
			await page.setInputFiles('input[type="file"]', drumOffGridPath);
			await expect(page.getByRole('button', { name: 'Convert to DTX' })).toBeVisible({
				timeout: 10000
			});
			await page.getByRole('button', { name: 'Convert to DTX' }).click();
			await expect(page.getByRole('button', { name: '✓ Converted' })).toBeVisible({
				timeout: 10000
			});

			await expect(page.getByText('Converted 6 note events')).toBeVisible();
			await expect(page.getByText('1 note(s) had no lane mapping')).toBeVisible();
			await expect(page.getByText('1 note(s) on non-drum channels ignored')).toBeVisible();

			const downloadPromise = page.waitForEvent('download');
			await page.getByRole('button', { name: 'Download DTX File' }).click();
			const download = await downloadPromise;
			expect(download.suggestedFilename()).toBe('drum-off-grid.dtx');
			const dtxText = await readDownload(download);

			const reparsed = parseHeaders(dtxText);
			expect(reparsed.bpm).toBe(140);
			// Bar 2 is 3/4 (the file's mid-file meter change survives).
			expect(reparsed.parseMeasureLengths().get(2)).toBe(0.75);

			const hits = hitsByLane(dtxText);
			// Humanized ticks quantize to the 1/192 grid without collapsing.
			expect(hits.get('13')).toEqual([
				[0, 0],
				[1, 0]
			]);
			expect(hits.get('12')).toEqual([
				[0, 0.125],
				[0, 25 / 192]
			]);
			expect(hits.get('11')).toEqual([[0, 0.25]]);
			expect(hits.get('1A')).toEqual([[2, 22 / 192]]);
		});
	});
});
